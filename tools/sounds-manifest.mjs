#!/usr/bin/env node
// Writes app/sounds/manifest.js: which sound files exist, so games request only real files (no 404 probing).
// Banks: name1.ogg … nameN.ogg (consecutive from 1, the way games read them); singles: name.ogg / .mp3 / .wav.
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../app/sounds');
const files = new Set(readdirSync(DIR));
const names = new Set();
for (const f of files) { const m = f.match(/^([a-z]+?)(\d*)\.(ogg|mp3|wav)$/i); if (m) names.add(m[1]); }
const banks = {}, single = {};
for (const n of [...names].sort()) {
  let k = 0; while (files.has(`${n}${k + 1}.ogg`)) k++;
  banks[n] = k;
  if (!k) for (const ext of ['ogg', 'mp3', 'wav']) if (files.has(`${n}.${ext}`)) { single[n] = ext; break; }
}
const out = `// Generated by tools/sounds-manifest.mjs: sound banks (name1..nameN.ogg) and single files that exist.\n`
  + `window.SOUND_MANIFEST = ${JSON.stringify(Object.assign(banks, {single}))};\n`;
writeFileSync(join(DIR, 'manifest.js'), out);
console.log(`app/sounds/manifest.js: ${Object.keys(banks).length - 1} names, ${Object.values(banks).filter(v => typeof v === 'number').reduce((s, v) => s + v, 0)} bank files`);
